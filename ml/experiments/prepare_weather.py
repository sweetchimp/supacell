import hashlib
import json
import sys
from pathlib import Path

import pandas as pd

REPO_ROOT = Path(__file__).resolve().parents[2]
ML_ROOT = REPO_ROOT / "ml"
if str(ML_ROOT) not in sys.path:
    sys.path.insert(0, str(ML_ROOT))

from supacell_ml.weather import (  # noqa: E402
    ARCHIVE_BASE_URL,
    UCI_LOCATION,
    WEATHER_VARIABLES,
    build_weather_frame,
    fetch_weather,
    join_weather_to_household,
)

CLEANED_PATH = REPO_ROOT / "data" / "processed" / "household_power_hourly_REAL.csv"
RAW_PATH = REPO_ROOT / "data" / "raw" / "open_meteo_sceaux_ERA5_2006-2010_REAL.json"
JOINED_PATH = REPO_ROOT / "data" / "processed" / "household_power_hourly_weather_REAL.csv"
METADATA_PATH = REPO_ROOT / "data" / "processed" / "weather_join_metadata_REAL.json"
DOCS_PATH = REPO_ROOT / "docs" / "weather_data.md"

SOURCE_NOTE = "UCI documentation identifies the household location as Sceaux, 7 km from Paris, France."
LICENSE_NOTE = "Open-Meteo API data are offered under CC BY 4.0; the free tier is for non-commercial use."
CITATION_NOTE = "Zippenfenig, P. (2023). Open-Meteo.com Weather API [Computer software]. Zenodo. https://doi.org/10.5281/ZENODO.7970649; Hersbach et al. (2023). ERA5 hourly data on single levels from 1940 to present. ECMWF. https://doi.org/10.24381/cds.adbb2d47"


def build_docs(metadata):
    variables = ", ".join(f"`{item}`" for item in WEATHER_VARIABLES)
    return f"""# Weather data join (`real`)

## Source and location

{SOURCE_NOTE}

Weather was fetched from the Open-Meteo Historical Weather API archive endpoint
`{ARCHIVE_BASE_URL}` using ERA5, coordinates
`{UCI_LOCATION['latitude']}, {UCI_LOCATION['longitude']}` and timezone
`{UCI_LOCATION['timezone']}`. Coordinates were resolved with Open-Meteo geocoding for
Sceaux, Hauts-de-Seine, France; the dataset documentation itself supplies the place
name and distance from Paris, not coordinates.

Requested hourly variables: {variables}.

## Licence

{LICENSE_NOTE}

Attribution: Weather data by Open-Meteo.com, https://open-meteo.com/. Licence:
https://creativecommons.org/licenses/by/4.0/.

Citation: {CITATION_NOTE}

## Join settings

- Requested start date: `{metadata['start_date']}`.
- Requested end date: `{metadata['end_date']}`.
- Raw response: `{metadata['raw_file']}`; SHA-256: `{metadata['raw_sha256']}`.
- Joined hourly file: `{metadata['joined_file']}`.
- Household rows: `{metadata['household_rows']}`; weather rows: `{metadata['weather_rows']}`; joined rows: `{metadata['joined_rows']}`.
- Fall-back DST duplicates keep the first local wall-clock hour; spring-forward local gaps are linearly interpolated over one hour.
- Weather columns are reanalysis values for the Sceaux grid cell, not measurements at the house.

Generated by `ml/experiments/prepare_weather.py`.
"""


def main():
    household = pd.read_csv(CLEANED_PATH, parse_dates=["timestamp"])
    start = household["timestamp"].min().normalize().strftime("%Y-%m-%d")
    end = (household["timestamp"].max().normalize() + pd.Timedelta(days=1)).strftime(
        "%Y-%m-%d"
    )
    payload, url = fetch_weather(start, end, RAW_PATH)
    weather = build_weather_frame(payload)
    joined = join_weather_to_household(CLEANED_PATH, weather, JOINED_PATH)
    raw_digest = hashlib.sha256(RAW_PATH.read_bytes()).hexdigest()
    metadata = {
        "dataset_label": "real",
        "source": "Open-Meteo Historical Weather API",
        "endpoint": ARCHIVE_BASE_URL,
        "request_url": url,
        "model": "ERA5",
        "location": UCI_LOCATION,
        "location_note": SOURCE_NOTE,
        "license": LICENSE_NOTE,
        "citation": CITATION_NOTE,
        "start_date": start,
        "end_date": end,
        "variables": list(WEATHER_VARIABLES),
        "raw_file": str(RAW_PATH),
        "raw_sha256": raw_digest,
        "joined_file": str(JOINED_PATH),
        "household_rows": int(len(household)),
        "weather_rows": int(len(weather)),
        "joined_rows": int(len(joined)),
        "dst_rule": "fall-back duplicate keeps first; spring-forward gap linearly interpolated over one hour",
    }
    METADATA_PATH.write_text(
        json.dumps(metadata, indent=2), encoding="utf-8"
    )
    DOCS_PATH.write_text(build_docs(metadata), encoding="utf-8")
    print(f"raw={RAW_PATH}")
    print(f"joined={JOINED_PATH}")
    print(f"metadata={METADATA_PATH}")
    print(f"docs={DOCS_PATH}")
    print(f"weather_rows={len(weather)} joined_rows={len(joined)}")


if __name__ == "__main__":
    main()
